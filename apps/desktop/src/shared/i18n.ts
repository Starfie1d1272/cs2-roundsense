const messages: Record<Locale, Record<MessageKey, string>> = { "zh-CN": zhCN, en };

export type MessageParams = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function itemLabel(locale: Locale, item: ProductItemId): string {
  return translate(locale, `item.${item}` as MessageKey);
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "zh-CN" || value === "en";
}
